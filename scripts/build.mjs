import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Script } from 'node:vm';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const core = await readFile(path.join(root, 'src/core.js'), 'utf8');
const names = [...core.matchAll(/^export (?:async )?function (\w+)/gm)].map((match) => match[1]);
const entry = (await readFile(path.join(root, 'src/index.js'), 'utf8')).replace(
  /^import \* as core from ['"]\.\/core\.js['"];\r?\n/,
  ''
);
const bundle = `// Generated by npm run build. No runtime Node.js dependencies.\n(() => {\nconst core = (() => {\n${core.replace(
  /^export /gm,
  ''
)}\nreturn { ${names.join(', ')} };\n})();\n${entry}\n})();\n`;
new Script(bundle, { filename: 'dist/index.js' });
await mkdir(path.join(root, 'dist'), { recursive: true });
await writeFile(path.join(root, 'dist/index.js'), bundle);
console.log(`Built dist/index.js (${Buffer.byteLength(bundle)} bytes)`);
